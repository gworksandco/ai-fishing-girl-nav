// public/ 直下に画像ファイルを追加したら、このリストにファイル名を足すだけで
// ランダム表示の対象が増える（訪問のたびに違うナミが表示されるようにして、
// リピート訪問時の新鮮さ・SNSでのシェアしたくなる感を狙う）。
// ============================================================================

export const NAMI_PHOTOS: string[] = ['nami-avatar.webp', 'nami-2.webp', 'nami-3.webp'];

/** ランダムに1枚選んで公開パス（先頭に/を付けたもの）を返す。 */
export function pickRandomNamiPhoto(): string {
  const idx = Math.floor(Math.random() * NAMI_PHOTOS.length);
  return `/${NAMI_PHOTOS[idx]}`;
}
